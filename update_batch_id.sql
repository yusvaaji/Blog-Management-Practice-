-- Script untuk mengupdate BATCH_ID
-- Mengganti huruf terakhir dari 'b' menjadi 'x'
-- Dari: EF005719-C838-40B2-A172-E9175424995B
-- Menjadi: EF005719-C838-40B2-A172-E9175424995X

UPDATE GLIFE.dbo.APPLICATION_SAVING_TRX 
SET BATCH_ID = REPLACE(BATCH_ID, 'EF005719-C838-40B2-A172-E9175424995B', 'EF005719-C838-40B2-A172-E9175424995X')
WHERE REGNO = 'U20250901141818467004'
    AND BATCH_ID = 'EF005719-C838-40B2-A172-E9175424995B';

-- Verifikasi hasil update
SELECT REGNO, SEQ, BATCH_ID, TRANS_TYPE, FUND_CODE, THEDATE, ER_AMOUNT, EE_AMOUNT, DC, USERBY, USERDATE
FROM GLIFE.dbo.APPLICATION_SAVING_TRX 
WHERE REGNO = 'U20250901141818467004'
ORDER BY SEQ;